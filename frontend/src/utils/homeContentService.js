/**
 * Synchronous get from localStorage with merge.
 */
export function getHomeContent() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      return {
        hero: { ...DEFAULT_HOME_CONTENT.hero, ...parsed.hero },
        categories: mergeCategories(parsed.categories),
        story: { ...DEFAULT_HOME_CONTENT.story, ...parsed.story },
        reviews: { ...DEFAULT_HOME_CONTENT.reviews, ...parsed.reviews },
        callout: { ...DEFAULT_HOME_CONTENT.callout, ...parsed.callout }
      };
    }
  } catch (err) {
    console.warn('LocalStorage read error', err);
  }
  return DEFAULT_HOME_CONTENT;
}

/**
 * Load async from IndexedDB if available and populate cache.
 */
export async function getHomeContentAsync() {
  try {
    const db = await openIndexedDB();
    const tx = db.transaction(STORE_NAME, 'readonly');
    const store = tx.objectStore(STORE_NAME);
    const req = store.get(STORAGE_KEY);

    return new Promise((resolve) => {
      req.onsuccess = () => {
        if (req.result) {
          const parsed = req.result;
          const merged = {
            hero: { ...DEFAULT_HOME_CONTENT.hero, ...parsed.hero },
            categories: mergeCategories(parsed.categories),
            story: { ...DEFAULT_HOME_CONTENT.story, ...parsed.story },
            reviews: { ...DEFAULT_HOME_CONTENT.reviews, ...parsed.reviews },
            callout: { ...DEFAULT_HOME_CONTENT.callout, ...parsed.callout }
          };
          // Sync to localStorage if not there
          try {
            localStorage.setItem(STORAGE_KEY, JSON.stringify(merged));
          } catch (_) {}
          resolve(merged);
        } else {
          resolve(getHomeContent());
        }
      };
      req.onerror = () => resolve(getHomeContent());
    });
  } catch (err) {
    return getHomeContent();
  }
}

/**
 * Save to both localStorage and IndexedDB.
 */
export function saveHomeContent(newContent) {
  let savedLocal = false;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(newContent));
    savedLocal = true;
  } catch (err) {
    console.warn('LocalStorage save failed, relying on IndexedDB', err);
  }

  // Always save to IndexedDB as high-capacity backing store
  openIndexedDB().then((db) => {
    const tx = db.transaction(STORE_NAME, 'readwrite');
    const store = tx.objectStore(STORE_NAME);
    store.put(newContent, STORAGE_KEY);
  }).catch((err) => {
    console.warn('IndexedDB save failed', err);
  });

  // Dispatch events for same-window and cross-tab reactive updates
  try {
    window.dispatchEvent(new Event('captura_home_updated'));
    // Trigger storage event for other open tabs
    localStorage.setItem('captura_cms_ping', Date.now().toString());
  } catch (_) {}

  return true;
}

/**
 * Reset all CMS content to default fine-art style.
 */
export function resetHomeContent() {
  try {
    localStorage.removeItem(STORAGE_KEY);
    openIndexedDB().then((db) => {
      const tx = db.transaction(STORE_NAME, 'readwrite');
      const store = tx.objectStore(STORE_NAME);
      store.delete(STORAGE_KEY);
    }).catch(() => {});

    window.dispatchEvent(new Event('captura_home_updated'));
    localStorage.setItem('captura_cms_ping', Date.now().toString());
  } catch (err) {
    console.error('Reset error', err);
  }
  return DEFAULT_HOME_CONTENT;
}
